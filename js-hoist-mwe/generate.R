# Write the JavaScript odin2 generates for model.R. Which odin2 is used is set by R_LIBS (see run.sh).
# Usage: Rscript generate.R out.mjs
out <- commandArgs(TRUE)[[1]]
js <- odin2::odin_show_js("model.R", check_bounds = "disabled")
header <- sprintf("// Generated by odin2 %s from js-hoist-mwe/model.R", packageVersion("odin2"))
writeLines(c(header, js, "export default odin_system;"), out)
cat(sprintf("wrote %s (%d lines)\n", out, length(js)))
